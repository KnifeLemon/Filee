// Decompiling a Source engine model (#1526): the .mdl with its .vvd, .vtx, .phy and .ani becomes the folder studiomdl
// could build it again from:
//
//   <model>.qc               $modelname, body groups, LODs, materials and skins, attachments, hitboxes, pose
//                            parameters, sequences with their events, collision model and settings, key values
//   <body model>.smd         one reference SMD per body group model (its bones, bind pose and weights)
//   <body model>_lod<n>.smd  a model's LOD, when it differs from the one before
//   <model>_physics.smd      the convex pieces of the .phy
//   <model>_anims/<anim>.smd one animation SMD per animation, every frame of every bone
//
// Not written: flexes (facial animation, .vta), eyeballs, IK rules and chains, bone controllers, and the procedural
// bones of a .vrd; a model that uses them still compiles from the QC, without them.

using System.Globalization;
using System.Numerics;
using System.Text;
using Filee.Core.Conversion;

namespace Filee.Engines.Models3D;

/// <summary>Decompiles a Source engine model into a QC and its SMDs.</summary>
internal static class SourceDecompiler
{
    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    // studiohdr_t flags (studio.h) and the QC commands that set them.
    private static readonly (int Flag, string Command)[] ModelFlags =
    [
        (0x00010, "$staticprop"), (0x00004, "$opaque"), (0x00008, "$mostlyopaque"), (0x10000, "$ambientboost"),
        (0x20000, "$donotcastshadows"), (0x40000, "$casttextureshadows"),
    ];

    private const int StaticProp = 0x10;
    private const int AutogeneratedHitboxes = 0x1;
    private const int ConstantDirectionalLight = 0x2000;

    // mstudioseqdesc_t flags (studio.h) and the sequence options that set them.
    private static readonly (int Flag, string Option)[] SequenceFlags =
    [
        (0x0001, "loop"), (0x0002, "snap"), (0x0004, "delta"), (0x0008, "autoplay"), (0x0010, "post"), (0x0100, "realtime"),
        (0x0400, "hidden"), (0x4000, "worldspace"),
    ];

    /// <summary>An event whose type has this bit is named, not numbered (NEW_EVENT_STYLE).</summary>
    private const int NamedEvent = 0x400;

    /// <summary>
    /// The most bone poses (frames × bones) of all animations together: what the animation SMDs hold, about 60 bytes a
    /// pose, so a few gigabytes at most.
    /// </summary>
    public const long MaxBoneFrames = 50_000_000;

    /// <summary>
    /// Writes the decompiled <paramref name="mdlPath"/> into <paramref name="folder"/>, which exists and is empty; a model
    /// whose animations hold more than <paramref name="maxBoneFrames"/> bone poses is refused before anything is written.
    /// </summary>
    public static void Decompile(string mdlPath, string folder, CancellationToken cancellationToken, long maxBoneFrames = MaxBoneFrames)
    {
        var model = SourceModel.Load(mdlPath, cancellationToken);
        var details = SourceModelDetails.Read(model, cancellationToken);
        var boneFrames = details.Animations.Sum(a => (long)a.Frames * model.Bones.Count);
        if (boneFrames > maxBoneFrames)
            throw new ConversionRefusedException("error.document_too_large", $"animations of more than {maxBoneFrames} bone poses");
        var name = SafeName(Path.GetFileNameWithoutExtension(mdlPath));
        var basePath = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(mdlPath))!, Path.GetFileNameWithoutExtension(mdlPath));
        var files = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { name + ".qc" };
        string Unique(string stem, string extension = ".smd")
        {
            var file = stem + extension;
            for (var n = 2; !files.Add(file); n++)
                file = $"{stem}_{n}{extension}";
            return file;
        }

        // The commands in the order and layout decompiled QCs commonly have, so one from Filee reads like them.
        var qc = new StringBuilder();
        qc.Append(Invariant, $"// Decompiled by Filee from {Path.GetFileName(mdlPath)} (version {details.Version}).\n\n");
        qc.Append(Invariant, $"$modelname {Quote(model.Name)}\n\n");
        if ((details.Flags & StaticProp) != 0)
            qc.Append("$staticprop\n\n");

        var references = WriteBodyGroups(qc, details, folder, Unique, cancellationToken);
        WriteLods(qc, details, references, folder, Unique, cancellationToken);
        WriteModelSettings(qc, details);
        WriteMaterials(qc, details);
        WriteAttachments(qc, details);
        qc.Append(Invariant, $"$cbox {Vector(details.ViewMin)} {Vector(details.ViewMax)}\n\n");
        qc.Append(Invariant, $"$bbox {Vector(details.HullMin)} {Vector(details.HullMax)}\n\n");
        WriteDefineBones(qc, details);
        WriteHitboxes(qc, details);
        foreach (var pose in details.PoseParameters)
        {
            qc.Append(Invariant, $"$poseparameter {Quote(pose.Name)} {Number(pose.Start)} {Number(pose.End)}");
            qc.Append((pose.Flags & 1) != 0 ? $" loop {Number(pose.Loop)}\n" : "\n");
        }
        if (details.PoseParameters.Count > 0)
            qc.Append('\n');

        var aniPath = SourceModel.Companion(basePath, [".ani"]);
        var ani = aniPath is null ? null : SourceBytes.Read(aniPath);
        WriteAnimations(qc, details, ani, name, folder, cancellationToken);

        // studiomdl puts "models/" in front of an included model itself.
        foreach (var include in details.IncludeModels)
            qc.Append(Invariant, $"$includemodel {Quote(WithoutModelsFolder(include))}\n\n");

        var phyPath = SourceModel.Companion(basePath, [".phy"]);
        if (phyPath is not null)
            WritePhysics(qc, details, SourcePhysics.Read(phyPath), Unique(name + "_physics"), folder, cancellationToken);

        if (details.KeyValues.Length > 0)
            qc.Append("$keyvalues\n{\n").Append(Indent(details.KeyValues)).Append("\n}\n");

        File.WriteAllText(Path.Combine(folder, name + ".qc"), qc.ToString(), new UTF8Encoding(false));
    }

    /// <summary>
    /// $surfaceprop, $contents, $illumposition, $eyeposition and the model's flags. studiomdl reads the illumination and
    /// eye positions turned a quarter about Z (it stores QC (x, y) as (−y, x)), so they are turned back.
    /// </summary>
    private static void WriteModelSettings(StringBuilder qc, SourceModelDetails details)
    {
        if (details.SurfaceProperty.Length > 0)
            qc.Append(Invariant, $"$surfaceprop {Quote(details.SurfaceProperty)}\n\n");
        qc.Append("$contents ").AppendJoin(' ', ContentsNames(details.Contents).Select(Quote)).Append("\n\n");
        qc.Append(Invariant, $"$illumposition {Vector(AsWritten(details.IlluminationPosition))}\n\n");
        if (details.EyePosition != Vector3.Zero)
            qc.Append(Invariant, $"$eyeposition {Vector(AsWritten(details.EyePosition))}\n\n");
        var flags = ModelFlags.Where(f => f.Flag != StaticProp && (details.Flags & f.Flag) != 0).ToList();
        foreach (var (_, command) in flags)
            qc.Append(command).Append('\n');
        if ((details.Flags & ConstantDirectionalLight) != 0)
            qc.Append(Invariant, $"$constantdirectionallight {Number(details.DirectionalLightDot / 255f)}\n");
        if (flags.Count > 0 || (details.Flags & ConstantDirectionalLight) != 0)
            qc.Append('\n');
    }

    /// <summary>A position as the QC wrote it, before studiomdl turned it: (x, y, z) stored is (y, −x, z) in the QC.</summary>
    private static Vector3 AsWritten(Vector3 stored) => new(stored.Y, -stored.X, stored.Z);

    // bspflags.h's CONTENTS_ values that $contents names.
    private static readonly (int Flag, string Name)[] Contents =
    [
        (0x1, "solid"), (0x8, "grate"), (0x2000000, "monster"), (0x20000000, "ladder"),
    ];

    private static IEnumerable<string> ContentsNames(int contents) =>
        contents == 0 ? ["notsolid"] : Contents.Where(c => (contents & c.Flag) != 0).Select(c => c.Name).DefaultIfEmpty("solid");

    private static string WithoutModelsFolder(string path)
    {
        var normal = path.Replace('\\', '/');
        return normal.StartsWith("models/", StringComparison.OrdinalIgnoreCase) ? normal["models/".Length..] : normal;
    }

    /// <summary>
    /// A $definebone line for every bone: its parent, its position and its rotation as pitch, yaw and roll in degrees
    /// (the rotations about Y, Z and X), and no fix-up.
    /// </summary>
    private static void WriteDefineBones(StringBuilder qc, SourceModelDetails details)
    {
        var bones = details.Model.Bones;
        foreach (var bone in bones)
        {
            var parent = bone.Parent >= 0 && bone.Parent < bones.Count ? bones[bone.Parent].Name : "";
            var r = bone.Rotation * (180 / MathF.PI);
            qc.Append(Invariant, $"$definebone {Quote(bone.Name)} {Quote(parent)} {Vector(bone.Position)} {Number(r.Y)} {Number(r.Z)} {Number(r.X)} 0 0 0 0 0 0\n");
        }
        if (bones.Count > 0)
            qc.Append("\n\n");
    }

    /// <summary>
    /// The $bodygroup blocks and a reference SMD for every body group model with triangles. Returns the file name
    /// written for each body model (null for a blank one), by body part and model.
    /// </summary>
    private static List<List<string?>> WriteBodyGroups(StringBuilder qc, SourceModelDetails details, string folder,
        Func<string, string, string> unique, CancellationToken cancellationToken)
    {
        var references = new List<List<string?>>();
        foreach (var part in details.BodyParts)
        {
            var files = new List<string?>();
            qc.Append(Invariant, $"$bodygroup {Quote(part.Name)}\n{{\n");
            foreach (var bodyModel in part.Models)
            {
                var meshes = bodyModel.Lods.Count > 0 ? bodyModel.Lods[0].Meshes : [];
                if (meshes.Count == 0)
                {
                    files.Add(null);
                    qc.Append("\tblank\n");
                    continue;
                }
                var stem = SafeName(Path.GetFileNameWithoutExtension(bodyModel.Name.Replace('\\', '/')));
                var file = unique(stem.Length > 0 ? stem : SafeName(part.Name) is { Length: > 0 } partStem ? partStem : "body", ".smd");
                WriteSmd(folder, file, stream => SmdFormat.WriteSkeletal(details.Model, meshes, stream, cancellationToken));
                files.Add(file);
                qc.Append(Invariant, $"\tstudio {Quote(file)}\n");
            }
            qc.Append("}\n\n");
            references.Add(files);
        }
        qc.Append('\n');
        return references;
    }

    /// <summary>
    /// A $lod block (or $shadowlod) for each LOD after the first: models whose triangles change get their own SMD
    /// (shared with the LOD before when the same), models with none are removed.
    /// </summary>
    private static void WriteLods(StringBuilder qc, SourceModelDetails details, List<List<string?>> references, string folder,
        Func<string, string, string> unique, CancellationToken cancellationToken)
    {
        var lods = details.BodyParts.SelectMany(p => p.Models).Select(m => m.Lods.Count).DefaultIfEmpty(0).Max();
        // The file each model's LOD so far uses, to reuse it when the next LOD is the same.
        var current = references.Select(files => files.ToList()).ToList();
        var currentMeshes = details.BodyParts.Select(p => p.Models.Select(m => m.Lods.Count > 0 ? m.Lods[0].Meshes : []).ToList()).ToList();
        for (var lod = 1; lod < lods; lod++)
        {
            var switchPoint = details.BodyParts.SelectMany(p => p.Models).Where(m => m.Lods.Count > lod).Select(m => m.Lods[lod].SwitchPoint).FirstOrDefault();
            var block = new StringBuilder();
            for (var p = 0; p < details.BodyParts.Count; p++)
            {
                for (var m = 0; m < details.BodyParts[p].Models.Count; m++)
                {
                    var bodyModel = details.BodyParts[p].Models[m];
                    var reference = references[p][m];
                    if (reference is null || bodyModel.Lods.Count <= lod)
                        continue;
                    var meshes = bodyModel.Lods[lod].Meshes;
                    if (meshes.Count == 0)
                    {
                        block.Append(Invariant, $"\tremovemodel {Quote(reference)}\n");
                        continue;
                    }
                    if (!SameMeshes(meshes, currentMeshes[p][m]))
                    {
                        current[p][m] = unique($"{Path.GetFileNameWithoutExtension(reference)}_lod{lod}", ".smd");
                        currentMeshes[p][m] = meshes;
                        var file = current[p][m]!;
                        WriteSmd(folder, file, stream => SmdFormat.WriteSkeletal(details.Model, meshes, stream, cancellationToken));
                    }
                    if (!string.Equals(current[p][m], reference, StringComparison.OrdinalIgnoreCase))
                        block.Append(Invariant, $"\treplacemodel {Quote(reference)} {Quote(current[p][m]!)}\n");
                }
            }
            qc.Append(switchPoint < 0 ? "$shadowlod\n" : $"$lod {Number(switchPoint)}\n").Append("{\n").Append(block).Append("}\n");
        }
        if (lods > 1)
            qc.Append('\n');
    }

    private static bool SameMeshes(List<SourceModel.Mesh> a, List<SourceModel.Mesh> b) =>
        a.Count == b.Count && a.Zip(b).All(pair => pair.First.Material == pair.Second.Material && pair.First.Triangles.SequenceEqual(pair.Second.Triangles));

    /// <summary>$cdmaterials, and $texturegroup with the textures that differ between skins.</summary>
    private static void WriteMaterials(StringBuilder qc, SourceModelDetails details)
    {
        foreach (var path in details.MaterialFolders)
            qc.Append(Invariant, $"$cdmaterials {Quote(path)}\n");
        if (details.SkinFamilies.Count > 1)
        {
            var first = details.SkinFamilies[0];
            var columns = Enumerable.Range(0, first.Length)
                .Where(c => details.SkinFamilies.Any(row => row[c] != first[c]))
                .Where(c => details.SkinFamilies.All(row => row[c] >= 0 && row[c] < details.Textures.Count))
                .ToList();
            if (columns.Count > 0)
            {
                qc.Append("$texturegroup \"skinfamilies\"\n{\n");
                foreach (var row in details.SkinFamilies)
                    qc.Append("\t{ ").AppendJoin(' ', columns.Select(c => Quote(details.Textures[row[c]]))).Append(" }\n");
                qc.Append("}\n");
            }
        }
        qc.Append('\n');
    }

    private static void WriteAttachments(StringBuilder qc, SourceModelDetails details)
    {
        var bones = details.Model.Bones;
        foreach (var attachment in details.Attachments)
        {
            if (attachment.Bone < 0 || attachment.Bone >= bones.Count)
                continue;
            // The QC's "rotate" takes pitch, yaw and roll in degrees: the rotations about Y, Z and X.
            var r = attachment.Rotation * (180 / MathF.PI);
            qc.Append(Invariant, $"$attachment {Quote(attachment.Name)} {Quote(bones[attachment.Bone].Name)} {Vector(attachment.Position)}");
            qc.Append(Invariant, $" rotate {Number(r.Y)} {Number(r.Z)} {Number(r.X)}\n");
        }
        if (details.Attachments.Count > 0)
            qc.Append('\n');
    }

    /// <summary>The hitboxes, unless studiomdl made them itself (then a recompile makes them again).</summary>
    private static void WriteHitboxes(StringBuilder qc, SourceModelDetails details)
    {
        if ((details.Flags & AutogeneratedHitboxes) != 0)
            return;
        var bones = details.Model.Bones;
        foreach (var set in details.HitboxSets.Where(s => s.Boxes.Count > 0))
        {
            qc.Append(Invariant, $"$hboxset {Quote(set.Name)}\n");
            foreach (var box in set.Boxes.Where(b => b.Bone >= 0 && b.Bone < bones.Count))
                qc.Append(Invariant, $"$hbox {box.Group} {Quote(bones[box.Bone].Name)} {Vector(box.Min)} {Vector(box.Max)}\n");
            qc.Append('\n');
        }
    }

    /// <summary>One animation SMD per animation in "&lt;model&gt;_anims", and the $sequence blocks that use them.</summary>
    private static void WriteAnimations(StringBuilder qc, SourceModelDetails details, SourceBytes? ani, string name, string folder,
        CancellationToken cancellationToken)
    {
        if (details.Animations.Count == 0)
            return;
        var animFolder = name + "_anims";
        Directory.CreateDirectory(Path.Combine(folder, animFolder));
        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var paths = new List<string>();
        foreach (var animation in details.Animations)
        {
            var stem = SafeName(animation.Name.TrimStart('@'));
            if (stem.Length == 0)
                stem = "anim";
            var file = stem + ".smd";
            for (var n = 2; !used.Add(file); n++)
                file = $"{stem}_{n}.smd";
            var frames = SourceAnimation.Decode(details, animation, ani, cancellationToken);
            WriteSmd(Path.Combine(folder, animFolder), file, stream => SmdFormat.WriteAnimation(details.Model.Bones, frames, stream, cancellationToken));
            paths.Add($"{animFolder}\\{file}");
        }

        // $sectionframes before the animations: the frames a section holds, and the fewest frames an animation needs to be
        // cut into sections (the shortest one that was).
        var sectioned = details.Animations.Where(a => a.SectionFrames > 0).ToList();
        if (sectioned.Count > 0)
            qc.Append(Invariant, $"$sectionframes {sectioned[0].SectionFrames} {sectioned.Min(a => a.Frames)}\n\n");

        var referenced = new HashSet<int>(details.Sequences.SelectMany(s => s.Animations));
        for (var a = 0; a < details.Animations.Count; a++)
        {
            if (!referenced.Contains(a))
                qc.Append(Invariant, $"$animation {Quote(details.Animations[a].Name.TrimStart('@'))} {Quote(paths[a])} fps {Number(details.Animations[a].Fps)}\n");
        }
        foreach (var sequence in details.Sequences)
            WriteSequence(qc, details, sequence, paths);
    }

    private static void WriteSequence(StringBuilder qc, SourceModelDetails details, SourceModelDetails.Sequence sequence, List<string> paths)
    {
        var first = details.Animations[sequence.Animations[0]];
        qc.Append(Invariant, $"$sequence {Quote(sequence.Name)} {{\n");
        foreach (var animation in sequence.Animations)
            qc.Append(Invariant, $"\t{Quote(paths[animation])}\n");
        if (sequence.Activity.Length > 0)
            qc.Append(Invariant, $"\tactivity {Quote(sequence.Activity)} {sequence.ActivityWeight}\n");
        qc.Append(Invariant, $"\tfadein {Number(sequence.FadeIn)}\n");
        qc.Append(Invariant, $"\tfadeout {Number(sequence.FadeOut)}\n");
        qc.Append(Invariant, $"\tfps {Number(first.Fps)}\n");
        foreach (var (flag, option) in SequenceFlags)
        {
            if ((sequence.Flags & flag) != 0)
                qc.Append('\t').Append(option).Append('\n');
        }
        var motion = SourceAnimation.ReadMovements(details.Model.Mdl, first.Offset).Aggregate(0, (flags, m) => flags | m.Flags);
        var motionNames = SourceAnimation.MotionFlags.Where(f => (motion & f.Flag) != 0).Select(f => f.Name).ToList();
        if (motionNames.Count > 0)
            qc.Append('\t').AppendJoin(' ', motionNames).Append('\n');
        if (sequence.Animations.Count > 1)
        {
            qc.Append(Invariant, $"\tblendwidth {sequence.BlendWidth}\n");
            for (var p = 0; p < 2; p++)
            {
                var index = sequence.Parameters[p];
                if (index >= 0 && index < details.PoseParameters.Count)
                    qc.Append(Invariant, $"\tblend {Quote(details.PoseParameters[index].Name)} {Number(sequence.ParameterStart[p])} {Number(sequence.ParameterEnd[p])}\n");
            }
        }
        foreach (var e in sequence.Events)
        {
            var frame = (int)MathF.Round(e.Cycle * Math.Max(first.Frames - 1, 0));
            var id = (e.Type & NamedEvent) != 0 && e.Name.Length > 0 ? e.Name : e.Event.ToString(Invariant);
            qc.Append(Invariant, $"\t{{ event {id} {frame} {Quote(e.Options)} }}\n");
        }
        qc.Append("}\n\n");
    }

    /// <summary>
    /// The physics SMD and its $collisionmodel, or $collisionjoints when every solid is named after a bone (a ragdoll,
    /// whose pieces are in their bones' space and are moved into the model's).
    /// </summary>
    private static void WritePhysics(StringBuilder qc, SourceModelDetails details, SourcePhysics physics, string file, string folder,
        CancellationToken cancellationToken)
    {
        var bones = details.Model.Bones;
        if (physics.Checksum != details.Checksum || physics.Solids.Count == 0)
        {
            qc.Append("// The .phy beside the model belongs to another build of it, so no collision model is written.\n\n");
            return;
        }
        var boneIndex = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        for (var i = 0; i < bones.Count; i++)
            boneIndex.TryAdd(bones[i].Name, i);
        var solidBlocks = physics.Blocks.Where(b => b.Name.Equals("solid", StringComparison.OrdinalIgnoreCase)).ToList();
        string? SolidName(int solid) =>
            solidBlocks.FirstOrDefault(b => b.Values.GetValueOrDefault("index") == solid.ToString(Invariant))?.Values.GetValueOrDefault("name");
        var joints = Enumerable.Range(0, physics.Solids.Count).All(s => SolidName(s) is { } bone && boneIndex.ContainsKey(bone));
        var edit = physics.Blocks.FirstOrDefault(b => b.Name.Equals("editparams", StringComparison.OrdinalIgnoreCase))?.Values
            ?? new Dictionary<string, string>();
        var root = edit.GetValueOrDefault("rootname") is { Length: > 0 } rootName && boneIndex.TryGetValue(rootName, out var rootBone) ? rootBone : 0;
        var world = WorldMatrices(bones);

        var pieces = new List<(int Bone, IReadOnlyList<Vector3> Points, IReadOnlyList<int> Triangles)>();
        for (var s = 0; s < physics.Solids.Count; s++)
        {
            var bone = joints ? boneIndex[SolidName(s)!] : root;
            foreach (var piece in physics.Solids[s].Pieces)
            {
                IReadOnlyList<Vector3> points = joints && bone < world.Length
                    ? piece.Points.Select(p => Vector3.Transform(p, world[bone])).ToList()
                    : piece.Points;
                pieces.Add((bone, points, piece.Triangles));
            }
        }
        WriteSmd(folder, file, stream => SmdFormat.WritePhysics(bones, pieces, stream, cancellationToken));

        var firstSolid = solidBlocks.FirstOrDefault()?.Values ?? new Dictionary<string, string>();
        qc.Append(Invariant, $"{(joints ? "$collisionjoints" : "$collisionmodel")} {Quote(file)}\n{{\n");
        var mass = edit.GetValueOrDefault("totalmass") ?? firstSolid.GetValueOrDefault("mass");
        if (mass is not null)
            qc.Append(Invariant, $"\t$mass {Value(mass)}\n");
        foreach (var key in new[] { "inertia", "damping", "rotdamping" })
        {
            if (firstSolid.GetValueOrDefault(key) is { } value)
                qc.Append(Invariant, $"\t${key} {Value(value)}\n");
        }
        if (edit.GetValueOrDefault("rootname") is { Length: > 0 } rootBoneName)
            qc.Append(Invariant, $"\t$rootbone {Quote(rootBoneName)}\n");
        if (!joints && (edit.GetValueOrDefault("concave") == "1" || pieces.Count > 1))
            qc.Append("\t$concave\n");
        if (pieces.Count > 20)
            qc.Append(Invariant, $"\t$maxconvexpieces {pieces.Count}\n");
        if (joints)
        {
            foreach (var constraint in physics.Blocks.Where(b => b.Name.Equals("ragdollconstraint", StringComparison.OrdinalIgnoreCase)))
            {
                if (!int.TryParse(constraint.Values.GetValueOrDefault("child"), NumberStyles.Integer, Invariant, out var child)
                    || SolidName(child) is not { } childBone)
                    continue;
                foreach (var axis in new[] { "x", "y", "z" })
                {
                    var min = Value(constraint.Values.GetValueOrDefault(axis + "min") ?? "0");
                    var max = Value(constraint.Values.GetValueOrDefault(axis + "max") ?? "0");
                    var friction = Value(constraint.Values.GetValueOrDefault(axis + "friction") ?? "0");
                    qc.Append(min == "0" && max == "0"
                        ? $"\t$jointconstrain {Quote(childBone)} {axis} fixed\n"
                        : $"\t$jointconstrain {Quote(childBone)} {axis} limit {min} {max} {friction}\n");
                }
            }
        }
        qc.Append("}\n\n");
    }

    /// <summary>Each bone's bind pose in model space (System.Numerics' row-vector matrices).</summary>
    internal static Matrix4x4[] WorldMatrices(IReadOnlyList<SourceModel.Bone> bones)
    {
        var world = new Matrix4x4[bones.Count];
        for (var i = 0; i < bones.Count; i++)
        {
            var local = Matrix4x4.CreateFromQuaternion(SourceAnimation.FromEuler(bones[i].Rotation)) * Matrix4x4.CreateTranslation(bones[i].Position);
            // Bones are stored parents first; a parent that comes later (a damaged file) is treated as none.
            var parent = bones[i].Parent;
            world[i] = parent >= 0 && parent < i ? local * world[parent] : local;
        }
        return world;
    }

    private static void WriteSmd(string folder, string file, Action<Stream> write)
    {
        using var stream = new FileStream(Path.Combine(folder, file), FileMode.CreateNew, FileAccess.Write, FileShare.None, 1 << 16);
        write(stream);
    }

    /// <summary>
    /// A file name made of the name's letters, digits and "-_." (others become "_"); a name Windows keeps for a device
    /// (con, prn, aux, nul, com1–com9, lpt1–lpt9, with any extension) gets a "_" in front.
    /// </summary>
    internal static string SafeName(string name)
    {
        var chars = name.Select(c => char.IsLetterOrDigit(c) || c is '-' or '_' or '.' ? c : '_').ToArray();
        var safe = new string(chars).Trim('.');
        var stem = safe.Split('.')[0];
        return IsDeviceName(stem) ? "_" + safe : safe;
    }

    private static bool IsDeviceName(string stem)
    {
        var lower = stem.ToLowerInvariant();
        return lower is "con" or "prn" or "aux" or "nul"
            || (lower.Length == 4 && (lower.StartsWith("com", StringComparison.Ordinal) || lower.StartsWith("lpt", StringComparison.Ordinal))
                && lower[3] is >= '1' and <= '9');
    }

    private static string Quote(string text) => "\"" + text.Replace('"', '\'') + "\"";

    /// <summary>A number with up to six decimals, never "-0".</summary>
    private static string Number(float value)
    {
        var text = value.ToString("0.######", Invariant);
        return text == "-0" ? "0" : text;
    }

    private static string Vector(Vector3 v) => $"{Number(v.X)} {Number(v.Y)} {Number(v.Z)}";

    /// <summary>A number from the .phy's text as the QC writes it.</summary>
    private static string Value(string text) =>
        float.TryParse(text, NumberStyles.Float, Invariant, out var value) ? Number(value) : "0";

    private static string Indent(string text) => string.Join('\n', text.Split('\n').Select(line => "\t" + line.Trim()));
}
