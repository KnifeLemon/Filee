    [Fact]
    public void The_drawing_is_framed_on_the_part_and_coloured_by_height()
    {
        var svg = GcodeDrawing.ToSvg(GcodeDrawing.Build(Read(Print), GcodeView.Top));

        // 20 mm of square, plus a margin each side; the first layer is the darkest colour, the last the lightest.
        Assert.Matches("""width="2[0-9.]*mm" height="2[0-9.]*mm" """, svg);
        Assert.Contains("stroke=\"#2C115F\"", svg);
        Assert.Contains("stroke=\"#FD9567\"", svg);
        Assert.Contains("stroke=\"#1C7ED6\"", svg); // travel
        Assert.Contains("stroke-width=\"0.66\"", svg); // the 0.6 mm nozzle's line
        var iso = GcodeDrawing.ToSvg(GcodeDrawing.Build(Read(Print), GcodeView.Isometric));
        Assert.NotEqual(svg, iso);
    }

    // ───────────────────────── Thumbnails ─────────────────────────

    private static string Base64Lines(byte[] data) =>
        string.Join('\n', Convert.ToBase64String(data).Chunk(78).Select(c => "; " + new string(c)));

    private static byte[] Picture(uint width, uint height, MagickFormat format, MagickColor color)
    {
        using var image = new MagickImage(color, width, height);
        return image.ToByteArray(format);
    }

    private static string WithThumbnails(params (string Header, byte[] Data, int Width, int Height)[] thumbnails) =>
        string.Concat(thumbnails.Select(t =>
            $"; {t.Header} begin {t.Width}x{t.Height} {Convert.ToBase64String(t.Data).Length}\n{Base64Lines(t.Data)}\n; {t.Header} end\n;\n"))
        + Print;

    [Fact]
    public void The_largest_thumbnail_is_found_whatever_its_header_says()
    {
        var small = Picture(16, 16, MagickFormat.Png, MagickColors.Red);
        var large = Picture(64, 32, MagickFormat.Jpeg, MagickColors.Blue);
        var qoi = Picture(48, 24, MagickFormat.Qoi, MagickColors.Green);
        // Cura plug-ins write JPG under the plain header; a QOI comes from PrusaSlicer for Prusa printers.
        var gcode = WithThumbnails(("thumbnail", small, 16, 16), ("thumbnail", large, 64, 32), ("thumbnail_QOI", qoi, 48, 24));

        var found = GcodeThumbnail.Largest(new MemoryStream(Encoding.UTF8.GetBytes(gcode)), CancellationToken.None);

        Assert.NotNull(found);
        Assert.Equal((64, 32, "jpg"), (found.Width, found.Height, found.Format));
        Assert.Equal(large, found.Data);
        var onlyQoi = GcodeThumbnail.Largest(new MemoryStream(Encoding.UTF8.GetBytes(WithThumbnails(("thumbnail_QOI", qoi, 48, 24)))), CancellationToken.None);
        Assert.Equal("qoi", onlyQoi?.Format);
    }

    [Theory]
    [InlineData("; thumbnail begin 64x64 12\n; not base64 at all!\n; thumbnail end\n")] // broken base64
    [InlineData("; thumbnail begin 9999x9999 8\n; iVBORw0K\n; thumbnail end\n")] // past the side budget
    [InlineData("; thumbnail begin 64x64 8\n; iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==\n; thumbnail end\n")] // longer than declared
    [InlineData("; thumbnail begin 4x4 8\n; AAAAAAAA\n; thumbnail end\n")] // not a picture
