// G-code toolpaths (3D printers, CNC machines) drawn as SVG, PDF and pictures, and the slicer's preview saved in the file.
// Every file is written here, in the shapes slicers and CAM programs write: PrusaSlicer-like headers and layer comments,
// Cura's ";LAYER:", CAM programs' modal moves, arcs and inches.

using System.Numerics;
using System.Text;
using Filee.Core.Conversion;
using Filee.Core.Presets;
using Filee.Engines.Gcode;
using ImageMagick;

namespace Filee.Engines.Tests;

public class GcodeTests(EngineFixture fx) : IClassFixture<EngineFixture>
{
    private static GcodeToolpath.Toolpath Read(string gcode) =>
        GcodeToolpath.Read(new MemoryStream(Encoding.UTF8.GetBytes(gcode)), CancellationToken.None);

    private static Vector3[] Points(GcodeToolpath.Line line) => [.. line.Points];

    /// <summary>A 20 × 20 mm square of two layers, with a PrusaSlicer-like start (purge line), travel between and a park.</summary>
    private const string Print = """
        ; generated by PrusaSlicer 2.7.2
        ; thumbnail begin 2x1 4
        ; AAAA
        ; thumbnail end
        M83 ; relative extrusion
        G28 W ; home
        G1 Z0.2 F720
        G1 Y-3 F1000
        G1 X0 Y-3
        G1 X60 E9 F1000 ; purge line, before the first layer
        ;LAYER_CHANGE
        ;Z:0.2
        G1 X10 Y10 F9000 ; travel
        G1 X30 Y10 E1.2
        G1 X30 Y30 E1.2
        G1 X10 Y30 E1.2
        G1 X10 Y10 E1.2
        G1 E-0.8 ; retract
        ;LAYER_CHANGE
        ;Z:0.4
        G1 Z0.4
        G1 X20 Y20
        G1 E0.8
        G1 X25 Y20 E0.3
        M107
        G1 X0 Y200 F9000 ; park, the end G-code
        ; nozzle_diameter = 0.6
        """;

    [Fact]
    public void A_print_is_drawn_as_its_extrusion_and_travel_without_the_start_purge_line()
    {
        var toolpath = Read(Print);

        Assert.True(toolpath.IsPrinter);
        Assert.Equal(2, toolpath.Layers);
        Assert.Equal(0.6f, toolpath.NozzleDiameter);
        var work = toolpath.Work.ToList();
        Assert.Equal(2, work.Count);
        Assert.Equal([new(10, 10, 0.2f), new(30, 10, 0.2f), new(30, 30, 0.2f), new(10, 30, 0.2f), new(10, 10, 0.2f)], Points(work[0]));
        Assert.Equal([new(20, 20, 0.4f), new(25, 20, 0.4f)], Points(work[1]));
        // The purge line at Y -3 is the printer's start and the move to Y 200 its end, not the part.
        Assert.DoesNotContain(toolpath.Lines.SelectMany(l => l.Points), p => p.Y is < 0 or > 100);
        Assert.Contains(toolpath.Lines, l => l.Kind == GcodeToolpath.MoveKind.Travel && l.Points[^1] == new Vector3(20, 20, 0.4f));
    }

    [Fact]
    public void Absolute_extrusion_g92_and_cura_layers_are_followed()
    {
        var toolpath = Read("""
            ;FLAVOR:Marlin
            M82
            G92 E0
            G0 X0 Y0 Z0.3
            ;LAYER:0
            G1 X10 Y0 E1
            G1 X10 Y10 E1 ; E doesn't grow: a move
            G92 E0
            G1 X0 Y10 E0.5
            M83
            G91
            G1 X0 Y-5 E0.5 ; relative, E too (M83)
            G90 ; Klipper's G90 leaves E relative, and no slicer that wrote M83 relies on Marlin's
            G1 X0 Y0 E0.5
            """);

        Assert.True(toolpath.IsPrinter);
        Assert.Equal(1, toolpath.Layers);
        Assert.Equal(
            [[new(0, 0, 0.3f), new(10, 0, 0.3f)], [new(10, 10, 0.3f), new(0, 10, 0.3f), new(0, 5, 0.3f), new(0, 0, 0.3f)]],
            toolpath.Work.Select(Points));
    }

    [Fact]
    public void A_cnc_program_cuts_with_feed_moves_and_rapids_are_travel()
    {
        // Modal moves, inches, several words a line, line numbers, checksums and parenthesis comments.
        var toolpath = Read("""
            %
            (pocket)
            N10 G20 G90 G17
            N20 G0 X0 Y0 Z0.1
            N30 G1 Z-0.05 F10 *45
            N40 X1
            N50 Y1 (modal G1)
            N60 G0 Z0.1
            N70 X2 Y0
            M30
            %
            """);

        Assert.False(toolpath.IsPrinter);
        Assert.Equal(0, toolpath.Layers);
        var cut = Assert.Single(toolpath.Work);
        Assert.Equal([new(0, 0, 2.54f), new(0, 0, -1.27f), new(25.4f, 0, -1.27f), new(25.4f, 25.4f, -1.27f)], Points(cut));
        var rapid = toolpath.Lines.Last();
        Assert.Equal(GcodeToolpath.MoveKind.Travel, rapid.Kind);
        Assert.Equal(new Vector3(50.8f, 0, 2.54f), rapid.Points[^1]);
    }

    [Theory]
    [InlineData("G2 X20 Y0 I10 J0", -1)] // clockwise from (0, 0) around (10, 0): through (10, 10)
    [InlineData("G3 X20 Y0 I10 J0", 1)]  // counter-clockwise: through (10, -10)
    [InlineData("G2 X20 Y0 R10", -1)]
    [InlineData("G3 X20 Y0 R10", 1)]
    public void Arcs_go_the_way_they_turn(string arc, int below)
    {
        var line = Assert.Single(Read($"G0 X0 Y0\nG1 Z-1\n{arc}").Work);

        Assert.All(line.Points.Skip(1), p => Assert.Equal(10, Vector2.Distance(new Vector2(p.X, p.Y), new Vector2(10, 0)), 0.01f));
        Assert.Equal(new Vector3(20, 0, -1), line.Points[^1]);
        var middle = line.Points[line.Points.Count / 2];
        Assert.Equal(below < 0 ? 10 : -10, middle.Y, 0.5f);
    }

    [Fact]
    public void A_full_circle_and_a_helix_are_drawn()
    {
        var circle = Assert.Single(Read("G0 X10 Y0\nG1 Z-1\nG2 X10 Y0 I-10 J0 Z-3").Work);

        Assert.True(circle.Points.Count > 36);
        Assert.Equal(new Vector3(10, 0, -3), circle.Points[^1]);
        Assert.Contains(circle.Points, p => p.X < -9.9f); // around the far side
        Assert.Contains(circle.Points, p => p.Z is < -1.5f and > -2.5f); // descending on the way
    }

    [Fact]
