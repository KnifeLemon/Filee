    [Fact]
    public async Task The_isometric_view_shows_the_height()
    {
        var tower = new StringBuilder("M83\nG0 X0 Y0 Z0.2\n");
        for (var layer = 1; layer <= 50; layer++)
            tower.Append($";LAYER_CHANGE\nG0 X0 Y0\nG1 Z{layer * 0.2:0.0}\nG1 X10 Y0 E1\nG1 X10 Y10 E1\nG1 X0 Y10 E1\nG1 X0 Y0 E1\n".Replace(',', '.'));
        var path = Write("tower.gcode", tower.ToString());

        var top = await fx.ConvertAsync([path], new Preset { TargetFormat = "svg", Output = { FileNamePattern = "{name}_top" } });
        var iso = await fx.ConvertAsync([path], new Preset { TargetFormat = "svg", Gcode = { View = GcodeView.Isometric }, Output = { FileNamePattern = "{name}_iso" } });

        // From above a 10 mm tower is a square; seen isometric its 10 mm of height make it taller than wide.
        static (double W, double H) Size(string svg)
        {
            var m = System.Text.RegularExpressions.Regex.Match(svg, """width="([0-9.]+)mm" height="([0-9.]+)mm" """);
            return (double.Parse(m.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture), double.Parse(m.Groups[2].Value, System.Globalization.CultureInfo.InvariantCulture));
        }
        var (topW, topH) = Size(File.ReadAllText(top.Files[0].Outputs[0]));
        var (isoW, isoH) = Size(File.ReadAllText(iso.Files[0].Outputs[0]));
        Assert.Equal(topW, topH, 0.01);
        Assert.True(isoH > isoW, $"{isoW} × {isoH}");
    }
