    [Fact]
    public async Task The_slicer_preview_is_the_picture_when_the_preset_asks_for_it()
    {
        var thumbnail = Picture(120, 90, MagickFormat.Png, MagickColors.Orange);
        var path = Write("benchy.gcode", WithThumbnails(("thumbnail", Picture(16, 16, MagickFormat.Png, MagickColors.Red), 16, 16), ("thumbnail", thumbnail, 120, 90)));

        var job = await fx.ConvertAsync([path], new Preset { TargetFormat = "webp", Gcode = { View = GcodeView.Thumbnail } });

        Assert.Equal(JobState.Completed, job.State);
        using var image = new MagickImage(Assert.Single(job.Files[0].Outputs));
        Assert.Equal((120u, 90u), (image.Width, image.Height));
        Assert.Null(job.Files[0].NoticeKey);

        // SVG stays the toolpath.
        var svg = await fx.ConvertAsync([path], new Preset { TargetFormat = "svg", Gcode = { View = GcodeView.Thumbnail } });
        Assert.Contains("<path", File.ReadAllText(Assert.Single(svg.Files[0].Outputs)));
    }

