    {
        Assert.Null(GcodeThumbnail.Largest(new MemoryStream(Encoding.UTF8.GetBytes(header + "G1 X1 Y1 E1\n")), CancellationToken.None));
    }

    // ───────────────────────── Conversions ─────────────────────────

    private string Write(string name, string gcode)
    {
        var path = Path.Combine(fx.NewFolder(), name);
        File.WriteAllText(path, gcode);
        return path;
    }

    [Theory]
    [InlineData("svg")]
    [InlineData("pdf")]
    [InlineData("png")]
    [InlineData("jpg")]
    public async Task G_code_becomes_svg_pdf_and_pictures(string target)
    {
        var job = await fx.ConvertAsync([Write("square.gcode", Print)], new Preset { TargetFormat = target });

        Assert.Equal(JobState.Completed, job.State);
        var output = Assert.Single(job.Files[0].Outputs);
        Assert.Equal("." + target, Path.GetExtension(output));
        if (target == "svg")
        {
            Assert.Contains("<path", File.ReadAllText(output));
            using var drawing = Vector.SvgRenderer.Load(output); // well-formed: the vector engine reads it back
            Assert.True(drawing.Bounds.Width > 20);
        }
        else if (target == "pdf")
            Assert.StartsWith("%PDF", File.ReadAllText(output));
        else
        {
            using var image = new MagickImage(output);
            Assert.True(image.Width >= 1000); // drawn at its render size, not 20 pixels for 20 mm
        }
    }

